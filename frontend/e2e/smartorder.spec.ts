  await page.getByLabel('옵션 1 이름').fill('아보카도')
  await page.getByRole('button',{name:'메뉴 저장'}).click()
  await expect(page.getByRole('heading',{name:'E2E 트리플 버거'})).toBeVisible()
  await expect(customer.getByRole('button',{name:'E2E 트리플 버거 12,300원',exact:true})).toBeVisible({timeout:7000})
  await page.getByRole('button',{name:'E2E 트리플 버거 수정'}).click()
  await page.getByLabel('가격 (원)').fill('13000')
  await page.getByRole('button',{name:'메뉴 저장'}).click()
  await expect(customer.getByRole('button',{name:'E2E 트리플 버거 13,000원',exact:true})).toBeVisible({timeout:7000})
  await page.getByRole('switch',{name:'E2E 트리플 버거 판매 상태'}).click()
